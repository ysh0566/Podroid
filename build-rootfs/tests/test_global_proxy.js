'use strict';
const assert=require('node:assert/strict');
const {options,config,guard}=require('../files/usr/local/share/podroid-host-services/global-config');
const {validPacket}=require('../files/usr/local/share/podroid-host-services/socks-bridge');
assert.equal(options('quiet podroid.proxy_port=0').global,false);
assert.throws(()=>options('podroid.proxy_mode=global podroid.proxy_port=0'));
assert.throws(()=>options('podroid.proxy_mode=global podroid.proxy_port=18888 podroid.proxy_type=invalid'));
const http=config(options('podroid.proxy_mode=global podroid.proxy_port=18888'),'10.0.2.2','eth0');
assert.equal(http.route.final,'proxy');assert.equal(http.dns.servers[0].detour,'proxy');
assert.equal(http.dns.servers[0].tls.enabled,true);
assert(http.dns.servers.some(x=>x.type==='fakeip'));
assert.deepEqual(http.dns.rules[0].query_type,['A','AAAA']);
assert.equal(http.experimental.cache_file.store_fakeip,true);
assert(http.route.rules.some(x=>x.network==='udp'&&x.action==='reject'));
assert(!http.route.rules.some(x=>x.outbound==='lan'));
assert(http.inbounds[0].address.some(x=>x.includes(':')));
const socks=config({protocol:'socks5',bypassLan:true},'10.0.2.2','eth0');
assert.equal(socks.outbounds[0].server_port,18891);
assert(socks.route.rules.some(x=>x.outbound==='lan'));
assert(!socks.route.rules.some(x=>x.network==='udp'&&x.action==='reject'));
assert.throws(()=>config({protocol:'http'},'bad gateway','eth0'));
assert.throws(()=>guard({},'10.0.2.2',[],'eth0;bad'));
const early=guard({});assert(early.includes('counter drop'));assert(!early.includes('18888'));
const rules=guard({},'10.0.2.2',['10.0.2.15'],'eth0');
assert(rules.includes('hook postrouting'));assert(rules.includes('dnat ip to 172.29.255.2'));
assert(!rules.includes('flush ruleset'));assert(!rules.includes('0.0.0.0/0 accept'));
assert(validPacket(Buffer.from([0,0,0,1,1,1,1,1,0,53])));
assert(!validPacket(Buffer.from([0,0,1,1,1,1,1,1,0,53])));
assert(!validPacket(Buffer.from([0,0,0,3,255,1,1])));
console.log('PASS: global proxy modes, DNS detour, IPv6, UDP policy, input validation and fail-closed rules');
